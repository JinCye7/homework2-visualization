# 第三部分：程度副词词库（约 70 个词，带强度倍率）
# ======================================================================
# 程度副词会修饰紧随其后的情感词的强度。
# 倍率设计原则：
#   - 极度级（极其/超级/无比）→ 2.5x，表达最强烈的情绪
