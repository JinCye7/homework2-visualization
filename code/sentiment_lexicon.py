# ======================================================================
# 第四部分：否定词词库（约 20 个词）
# ======================================================================
# 否定词会翻转紧随其后的情感词的极性：
#   - 否定 + 正向词 → 负向含义（"不开心" = 消极）
#   - 否定 + 负向词 → 缓和积极（"不难过" = 略有积极）
# 注意："不是" 会匹配但 "不得了" 不会（算法中检查词边界）

NEGATION_WORDS = {
    "不", "没", "没有", "无", "别", "勿", "未", "非", "莫", "休",
    "不要", "不会", "不想", "不能", "不敢", "不再", "从不",
}


# ======================================================================
# 第五部分：句边界字符集
# ======================================================================
# 遇到这些字符时，重置当前的否定状态和副词倍率。
# 因为中文的子句之间在情感上相对独立，否定通常不跨句生效。
# 例如："虽然不开心，但是……" → 逗号后的"但是"不应受"不"影响。

SENTENCE_BOUNDARY = set("，。！？、；：…～—　 \t\r\n")


# ======================================================================
# 第六部分：预处理——程度副词正则预编译
# ======================================================================
# 将程度副词按长度降序排序（长词优先匹配，防止"越来越"被"越"误匹配），
# 编译为一条正则 OR 模式，供词典评分函数使用。

_ADVERB_SORTED = sorted(DEGREE_ADVERBS.keys(), key=len, reverse=True)
_ADVERB_PATTERN = re.compile("|".join(re.escape(a) for a in _ADVERB_SORTED))


# ======================================================================
# 第七部分：核心评分算法
# ======================================================================

def lexicon_sentiment_score(text: str) -> float:
    """
    基于中文情感词典的情感评分算法。

    【算法流程】
      逐字符遍历输入文本，在每个位置尝试匹配（按优先级）：
        1. 句边界字符 → 重置否定状态和副词倍率
        2. 程度副词（长词优先）→ 设置当前副词倍率
        3. 否定词（长词优先，含边界检查）→ 激活否定标志
        4. 情感词（长词优先，跳过单字词）→ 根据否定/副词计算分数
        5. 以上均不匹配 → i += 1 继续扫描

    【否定处理规则】
      - 否定 + 正向词：将分数计入 neg_score（否定正面 = 消极）
      - 否定 + 负向词：将分数 × 0.7 计入 pos_score（否定负面 ≠ 完全积极
        如"不难过"比"开心"弱，但比"难过"积极）
      - 匹配到情感词后：重置否定标志和副词倍率为默认值

    【边界条件】
      - 空文本或空白文本返回 0.5（中性默认值）
      - 没有任何情感词匹配时返回 0.5
      - 单字情感词被跳过（误匹配太多，如"爱"本身就是字）

    参数:
        text: 待评分的评论文本

    返回:
        float: 情感分数，范围约 [0, 1]，>0.5 为正向，<0.5 为负向
    """
    # 防御性检查：空文本或非字符串返回中性分
    if not isinstance(text, str) or not text.strip():
        return 0.5

    pos_score = 0.0   # 正向情感累计分数
    neg_score = 0.0   # 负向情感累计分数
    active_multiplier = 1.0   # 当前活跃的程度副词倍率（默认 1.0）
    negation_active = False   # 当前是否处于否定状态

    i = 0
    text_len = len(text)

    # ---- 逐字符扫描主循环 ----
    while i < text_len:
        ch = text[i]

        # -- 规则 1：句边界 → 重置状态 --
        # 中文标点符号后面的情感词不应受前面否定词影响
        if ch in SENTENCE_BOUNDARY:
            active_multiplier = 1.0
            negation_active = False

        # -- 规则 2：程度副词匹配（长词优先）--
        matched_adv = False
        for adv in _ADVERB_SORTED:
            adv_len = len(adv)
            if i + adv_len <= text_len and text[i:i + adv_len] == adv:
                active_multiplier = DEGREE_ADVERBS[adv]
                matched_adv = True
                i += adv_len   # 跳过副词本身
                break

        if matched_adv:
            continue  # 继续扫描后续的情感词

        # -- 规则 3：否定词匹配（长词优先，含词边界验证）--
        matched_neg = False
        for neg in sorted(NEGATION_WORDS, key=len, reverse=True):
            neg_len = len(neg)
            if i + neg_len <= text_len and text[i:i + neg_len] == neg:
                # 词边界验证：确保否定词是独立词，而非更大词的一部分
                # 例如："不是" → 匹配 ✓；"不得了" 中的 "不" → 不应匹配 ✗
                is_word_start = (i == 0 or text[i-1] not in set("得"))
                is_word_end = (i + neg_len >= text_len or
                              text[i + neg_len] in SENTENCE_BOUNDARY or
                              not text[i + neg_len].isalpha())
                if is_word_start:
                    negation_active = True
                    matched_neg = True
                    i += neg_len
                    break

        if matched_neg:
            continue  # 继续扫描后续的情感词

        # -- 规则 4：情感词匹配（长词优先，跳过单字词）--
        matched_sent = False
        # 先检查正向词库，再检查负向词库
        for sent_set, is_pos in [(POSITIVE_WORDS, True), (NEGATIVE_WORDS, False)]:
            sorted_sent = sorted(sent_set, key=len, reverse=True)
            for word in sorted_sent:
                w_len = len(word)
                # 跳过单字词：单字误匹配率太高
                # 例如"爱"会匹配"喜爱"中的"爱"导致重复计数
                if w_len == 1:
                    continue
                if i + w_len <= text_len and text[i:i + w_len] == word:
                    score = 1.0 * active_multiplier   # 基础分 × 副词强度

                    if negation_active:
                        # --- 否定状态下的情感极性翻转 ---
                        if is_pos:
                            # "不开心" → 负向情感，将分加入负向
                            neg_score += score
                        else:
                            # "不难过" → 缓和积极（×0.7 表示弱正向，
                            # 不像直接的正向词那么强烈）
                            pos_score += score * 0.7
                    else:
                        # --- 无否定，直接计入对应方向 ---
                        if is_pos:
                            pos_score += score
                        else:
                            neg_score += score

                    matched_sent = True
                    i += w_len
                    # 匹配到情感词后重置状态，下一个情感词重新判断
                    active_multiplier = 1.0
                    negation_active = False
                    break
            if matched_sent:
                break

        # -- 规则 5：当前位置无任何匹配 → 前进一步 --
        if not matched_sent:
            i += 1

    # ---- 最终得分计算 ----
    total = pos_score + neg_score
    if total == 0:
        return 0.5   # 无任何情感词 → 返回中性默认值
    # 得分 = 正向分占总分的比例
    return pos_score / total


# ======================================================================
# 第八部分：混合评分与情感分类
# ======================================================================

def hybrid_sentiment_score(text: str, snownlp_score: float = None) -> float:
    """
    混合情感评分：词典分 + SnowNLP分。

    【权重设计原理】
      - 词典分占 55%：基于人工标注的中文词库，对情感、诗意表达更准确
      - SnowNLP 占 45%：保留统计学习模型的泛化能力
      - 经验表明 55:45 的比例在中文音乐评论上取得最佳平衡：
        既纠正了 SnowNLP 过度正向的偏差，又保留了其对长文本的整体把握

    参数:
        text: 评论原始文本
        snownlp_score: SnowNLP 原始评分（0~1），为 None 时仅返回词典分

    返回:
        float: 混合情感分数，范围 [0, 1]
    """
    lex_score = lexicon_sentiment_score(text)
    if snownlp_score is None:
        return lex_score
    # 加权混合：词典 55% + SnowNLP 45%
    return 0.55 * lex_score + 0.45 * snownlp_score


def classify_sentiment(score: float) -> str:
    """
    将情感分数分类为 积极/中性/消极。

    【阈值设计原理】
      - >0.55 → 积极：必须有明显正向信号才判定为积极
      - 0.45~0.55 → 中性：中间地带留宽一些，减少误分类
      - <0.45 → 消极：低于中性区间即判定为消极

      相比原始 SnowNLP 的 0.6/0.4 阈值，这里的 0.55/0.45 更宽松，
      原因是混合评分后的分数分布更均匀，不再像 SnowNLP 那样集中在高分端。

    参数:
        score: 情感分数（0~1）

    返回:
        str: "积极" / "中性" / "消极"
    """
    if score > 0.55:
        return "积极"
    elif score >= 0.45:
        return "中性"
    else:
        return "消极"
